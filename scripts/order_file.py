#!/usr/bin/env python3
"""Write the linker order file of duit, `crates/duit/duit.order`, on macOS.

The scans to an export with one thread and the conversion of a binary export to JSON keep less than
1 MiB of heap, so the code that they keep resident counts in their peak memory. The order file puts
the functions that these paths run at the start of `__text`, grouped by the paths that run them, so
each path touches a few pages of code instead of most of the binary.

Builds duit with the release profile in `target/order-file/`, with a link map, runs each case on the
tree of `scripts/benchmark.py` under lldb with a breakpoint on every function, which removes itself
at its first hit, and names the functions that each case entered from the map. The symbol names
hold a hash of each crate, which changes with the profile, the target, the versions of the crates,
and the toolchain. The file lists the names of the release build, which `scripts/benchmark.py`
measures, and of a local `dist` build for the host. The linker ignores the
names that it does not find, so rerun this after a change to the code, the dependencies, or the
toolchain.

Usage: `make order` or `python3 scripts/order_file.py`. Needs lldb, from Xcode or its command line
tools, and generates the tree of `scripts/benchmark.py` if it is missing.
"""

import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "target" / "order-file"
ORDER = ROOT / "crates" / "duit" / "duit.order"

JSON_ONE = "scan to JSON, -t 1"
BINARY_ONE = "scan to binary, -t 1"
BINARY_FOUR = "scan to binary, -t 4"
IMPORT = "import binary to JSON"

# The groups of the functions that the same cases run, in the order of the file. Each case reads a
# run of adjacent groups, except for a few small groups, so its functions lie close together.
# Functions of a group that is not listed go last.
LAYOUT = [
    {BINARY_FOUR},
    {BINARY_ONE, BINARY_FOUR},
    {BINARY_ONE},
    {BINARY_ONE, BINARY_FOUR, IMPORT},
    {BINARY_ONE, BINARY_FOUR, JSON_ONE},
    {BINARY_ONE, JSON_ONE},
    {BINARY_ONE, BINARY_FOUR, JSON_ONE, IMPORT},
    {JSON_ONE},
    {JSON_ONE, IMPORT},
    {IMPORT},
]

HEADER = """\
# The functions that the streaming paths of duit run, for `-order_file` of the Apple linker.
# Generated by `scripts/order_file.py`, see BENCHMARKS.md.
"""

# The disambiguator of a crate in a v0 symbol name, such as `Csjnpgb3NJ0MC_` in `Csjnpgb3NJ0MC_4duit`.
CRATE_HASH = re.compile(r"Cs[0-9A-Za-z]+_(?=\d)")

entered = []


def record_entry(frame, location, extra_args, internal_dict):
    entered.append(frame.GetSymbol().GetStartAddress().GetFileAddress())
    location.SetEnabled(False)
    return False


def __lldb_init_module(debugger, internal_dict):
    """Run one case under lldb, from `command script import`, and write the functions it entered.

    The binary has no symbol table, so lldb names its functions from their start addresses.
    """
    import lldb

    target = debugger.CreateTarget(os.environ["ORDER_FILE_BINARY"])
    for symbol in target.GetModuleAtIndex(0):
        if symbol.GetType() == lldb.eSymbolTypeCode and symbol.GetStartAddress().IsValid():
            breakpoint = target.BreakpointCreateBySBAddress(symbol.GetStartAddress())
            breakpoint.SetScriptCallbackFunction(f"{__name__}.record_entry")
    launch = target.GetLaunchInfo()
    launch.SetArguments(json.loads(os.environ["ORDER_FILE_ARGUMENTS"]), False)
    debugger.SetAsync(False)
    error = lldb.SBError()
    process = target.Launch(launch, error)
    if not error.Success():
        sys.exit(f"lldb could not launch duit: {error}")
    while process.GetState() == lldb.eStateStopped:
        process.Continue()
    if process.GetState() != lldb.eStateExited or process.GetExitStatus() != 0:
        sys.exit(f"duit did not exit with 0 under lldb: {process}")
    Path(os.environ["ORDER_FILE_OUTPUT"]).write_text("".join(f"{address}\n" for address in entered))


def build(profile, map_path):
    """Build duit with a link map, and return the functions of its `__text` by their address."""
    command = ["cargo", "rustc", "--locked", "-p", "duit", "--bin", "duit", *profile]
    command += ["--", "-C", f"link-arg=-Wl,-map,{map_path}"]
    benchmark.run(command, cwd=ROOT, env=dict(os.environ, CARGO_TARGET_DIR=str(TARGET)))
    text, functions, section = None, {}, None
    for line in map_path.read_text(errors="replace").splitlines():
        if line.startswith("#"):
            section = line if line.endswith(":") else section
            continue
        fields = line.split("\t")
        if section == "# Sections:" and fields[3:4] == ["__text"]:
            start = int(fields[0], 16)
            text = range(start, start + int(fields[1], 16))
        elif section == "# Symbols:" and len(fields) == 3 and int(fields[0], 16) in text:
            functions[int(fields[0], 16)] = fields[2].split("] ", 1)[1]
    return functions


def trace(binary, arguments, output):
    environment = dict(os.environ)
    environment["ORDER_FILE_BINARY"] = str(binary)
    environment["ORDER_FILE_ARGUMENTS"] = json.dumps(["--ignore-config", "-0", *map(str, arguments)])
    environment["ORDER_FILE_OUTPUT"] = str(output)
    command = ["lldb", "--batch", "--no-lldbinit", "-o", f"command script import {__file__}"]
    benchmark.run(command, env=environment, stdout=subprocess.DEVNULL, cwd=TARGET)
    return [int(address) for address in output.read_text().split()]


def names_by_key(functions):
    """Return the function names of a build by their name without crate hashes, if unique."""
    names = {}
    for name in functions.values():
        key = CRATE_HASH.sub("Cs_", name)
        names[key] = None if key in names else name
    return names


def main():
    if sys.platform != "darwin":
        sys.exit("The order file is for the Apple linker, run this on macOS")
    host = re.search(r"^host: (\S+)$", benchmark.run(
        ["rustc", "-vV"], cwd=ROOT, capture_output=True, text=True
    ).stdout, re.MULTILINE).group(1)
    release = build(["--release"], TARGET / "release.map")
    dist = build(["--profile", "dist", "--target", host], TARGET / "dist.map")
    binary = TARGET / "release" / "duit"
    benchmark.prepare_tree()
    export = TARGET / "tree.ncdu"
    benchmark.run([binary, "--ignore-config", "-0", "-O", export, benchmark.TREE])

    cases = {
        JSON_ONE: ["-t", "1", "-o", "/dev/null", benchmark.TREE],
        BINARY_ONE: ["-t", "1", "-O", "/dev/null", benchmark.TREE],
        BINARY_FOUR: ["-t", "4", "-O", "/dev/null", benchmark.TREE],
        IMPORT: ["-f", export, "-o", "/dev/null"],
    }
    # The cases of each function, by its name without crate hashes, in the order of the first entry.
    cases_of = {}
    for index, (case, arguments) in enumerate(cases.items()):
        for address in trace(binary, arguments, TARGET / f"trace-{index}.txt"):
            if address in release:
                cases_of.setdefault(CRATE_HASH.sub("Cs_", release[address]), set()).add(case)

    groups = [[] for _ in range(len(LAYOUT) + 1)]
    for key, group in cases_of.items():
        groups[LAYOUT.index(group) if group in LAYOUT else len(LAYOUT)].append(key)
    builds = [names_by_key(release), names_by_key(dist)]
    lines = []
    for key in (key for group in groups for key in group):
        # A name that two functions of a build share, such as a static C function of two files,
        # would need the name of its object file, so it is left out.
        for name in dict.fromkeys(names[key] for names in builds if names.get(key)):
            lines.append(f"{name}\n")
    ORDER.write_text(HEADER + "".join(lines))
    print(f"Wrote {len(cases_of)} functions to {ORDER.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    # Imported here, because lldb imports this file without its directory on the path.
    sys.dont_write_bytecode = True
    import benchmark

    main()
