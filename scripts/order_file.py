#!/usr/bin/env python3

import json
import os
import re
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True
# After the line above, so that importing it writes no `__pycache__/` into `scripts/`.
import benchmark  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "target" / "order-file"
ORDER = ROOT / "crates" / "duit" / "duit.order"

JSON_ONE = "scan to JSON, -t 1"
BINARY_ONE = "scan to binary, -t 1"
BINARY_FOUR = "scan to binary, -t 4"
IMPORT = "import binary to JSON"

LAYOUT = [
    {BINARY_FOUR},
    {BINARY_ONE, BINARY_FOUR},
    {BINARY_ONE},
    {BINARY_ONE, BINARY_FOUR, IMPORT},
    {BINARY_ONE, BINARY_FOUR, JSON_ONE},
    {BINARY_ONE, JSON_ONE},
    {BINARY_ONE, BINARY_FOUR, JSON_ONE, IMPORT},
    {JSON_ONE},
    {JSON_ONE, IMPORT},
    {IMPORT},
]

HEADER = """\
# The functions that the streaming paths of duit run, for `-order_file` of the Apple linker.
# Generated by `scripts/order_file.py`, see BENCHMARKS.md.
"""

# A symbol line of a linker map: the address, the size, and the file and the name.
SYMBOL_FIELDS = 3

# The disambiguator of a crate in a v0 symbol name, such as `Csjnpgb3NJ0MC_` in `Csjnpgb3NJ0MC_4duit`.
CRATE_HASH = re.compile(r"Cs[0-9A-Za-z]+_(?=\d)")


def build(profile: list[str], map_path: Path) -> None:
    command = ["cargo", "rustc", "--locked", "-p", "duit", "--bin", "duit", *profile]
    command += ["--", "-C", f"link-arg=-Wl,-map,{map_path}"]
    benchmark.run(command, cwd=ROOT, env=dict(os.environ, CARGO_TARGET_DIR=str(TARGET)))


def text_functions_by_address(map_path: Path) -> dict[int, str]:
    text: range | None = None
    functions: dict[int, str] = {}
    section: str | None = None
    for line in map_path.read_text(errors="replace").splitlines():
        if line.startswith("#"):
            section = line if line.endswith(":") else section
            continue
        fields = line.split("\t")
        if section == "# Sections:" and fields[3:4] == ["__text"]:
            start = int(fields[0], 16)
            text = range(start, start + int(fields[1], 16))
        elif (
            section == "# Symbols:"
            and len(fields) == SYMBOL_FIELDS
            and text
            and int(fields[0], 16) in text
        ):
            functions[int(fields[0], 16)] = fields[2].split("] ", 1)[1]
    return functions


def trace(binary: Path, arguments: list[str | Path], output: Path) -> list[int]:
    environment = dict(os.environ)
    environment["ORDER_FILE_BINARY"] = str(binary)
    environment["ORDER_FILE_ARGUMENTS"] = json.dumps(
        ["--ignore-config", "-0", *map(str, arguments)]
    )
    environment["ORDER_FILE_OUTPUT"] = str(output)
    hook = Path(__file__).with_name("order_file_lldb.py")
    command = ["lldb", "--batch", "--no-lldbinit", "-o", f"command script import {hook}"]
    benchmark.run(command, env=environment, stdout=subprocess.DEVNULL, cwd=TARGET)
    return [int(address) for address in output.read_text().split()]


def unique_names_by_key(functions: dict[int, str]) -> dict[str, str]:
    names: dict[str, list[str]] = {}
    for name in functions.values():
        names.setdefault(CRATE_HASH.sub("Cs_", name), []).append(name)
    return {key: found[0] for key, found in names.items() if len(found) == 1}


def main() -> None:
    if sys.platform != "darwin":
        sys.exit("The order file is for the Apple linker, run this on macOS")
    host_line = re.search(
        r"^host: (\S+)$",
        benchmark.run(["rustc", "-vV"], cwd=ROOT, capture_output=True, text=True).stdout,
        re.MULTILINE,
    )
    if host_line is None:
        sys.exit("rustc -vV printed no host line")
    host = host_line.group(1)
    build(["--release"], TARGET / "release.map")
    build(["--profile", "dist", "--target", host], TARGET / "dist.map")
    release = text_functions_by_address(TARGET / "release.map")
    dist = text_functions_by_address(TARGET / "dist.map")
    binary = TARGET / "release" / "duit"
    benchmark.prepare_tree()
    export = TARGET / "tree.ncdu"
    benchmark.run([binary, "--ignore-config", "-0", "-O", export, benchmark.TREE])

    cases = {
        JSON_ONE: ["-t", "1", "-o", "/dev/null", benchmark.TREE],
        BINARY_ONE: ["-t", "1", "-O", "/dev/null", benchmark.TREE],
        BINARY_FOUR: ["-t", "4", "-O", "/dev/null", benchmark.TREE],
        IMPORT: ["-f", export, "-o", "/dev/null"],
    }
    cases_of = {}
    for index, (case, arguments) in enumerate(cases.items()):
        for address in trace(binary, arguments, TARGET / f"trace-{index}.txt"):
            if address in release:
                cases_of.setdefault(CRATE_HASH.sub("Cs_", release[address]), set()).add(case)

    groups = [[] for _ in range(len(LAYOUT) + 1)]
    for key, group in cases_of.items():
        groups[LAYOUT.index(group) if group in LAYOUT else len(LAYOUT)].append(key)
    builds = [unique_names_by_key(release), unique_names_by_key(dist)]
    lines = [
        f"{name}\n"
        for key in (key for group in groups for key in group)
        for name in dict.fromkeys(names[key] for names in builds if key in names)
    ]
    ORDER.write_text(HEADER + "".join(lines))
    print(f"Wrote {len(cases_of)} functions to {ORDER.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
