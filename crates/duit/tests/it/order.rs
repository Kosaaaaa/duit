use std::fs;
use std::path::Path;

use insta::assert_snapshot;

/// The names in the order file hold a hash of each crate, which changes with the version, and the
/// linker skips a name that it does not find. So the file names the version that it was written
/// for, and a version bump without `make order` fails here instead of losing the layout.
#[test]
fn order_file_is_of_this_version() {
    let order = fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("duit.order"))
        .expect("order file is read");
    let header: Vec<&str> = order
        .lines()
        .take_while(|line| line.starts_with('#'))
        .collect();
    assert_snapshot!(header.join("\n").replace(env!("CARGO_PKG_VERSION"), "[VERSION]"), @r"
    # The functions that the streaming paths of duit run, for `-order_file` of the Apple linker.
    # Generated by `scripts/order_file.py` for duit [VERSION], see BENCHMARKS.md.
    # The names hold a hash that changes with the version: run `make order` after a version bump.
    ");
}
